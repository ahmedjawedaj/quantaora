export function assetRealismCoverage() {
  const byBranch = new Map<string, AssetRealismTarget[]>()
  for (const target of ASSET_REALISM_WAVE1_TRACKER) {
    byBranch.set(target.branchId, [...(byBranch.get(target.branchId) ?? []), target])
  }

  return P1_ASSET_REALISM_BRANCHES.map((branchId) => {
    const targets = byBranch.get(branchId) ?? []
    return {
      branchId,
      upgradedExistingAssets: targets.filter((target) => target.status === 'upgraded-existing-asset').length,
      supportOnly: targets.filter((target) => target.status === 'support-only').length,
      readyForAuthenticatedImport: targets.filter((target) => target.status === 'ready-for-authenticated-import').length,
      readyForAttributionReview: targets.filter((target) => target.status === 'ready-for-attribution-review').length,
      needsSourcing: targets.filter((target) => target.status === 'needs-sourcing' || target.status === 'blocked-unoptimized').length,
      targets,
    }
  })
}
