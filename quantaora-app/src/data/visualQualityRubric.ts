export const BRANCH_VISUAL_QUALITY = PROFILE_ROWS

const PROFILE_BY_BRANCH: Map<string, BranchVisualQualityProfile> = new Map(
  BRANCH_VISUAL_QUALITY.map((profile) => [profile.branchId, profile]),
)

export function branchVisualQualityProfile(branchId: string): BranchVisualQualityProfile | undefined {
  return PROFILE_BY_BRANCH.get(branchId)
}

export function visualQualityNeedsReplacement(profile: BranchVisualQualityProfile | undefined): boolean {
  return profile?.replacementPriority === 'P1' || profile?.replacementPriority === 'P0 legal'
}
