function lesson(predictionPrompt: string, change: string, observe: string, explain: string) {
  return {
    steps: [
      { title: 'Predict', body: predictionPrompt },
      { title: 'Change', body: change },
      { title: 'Observe', body: observe },
      { title: 'Explain', body: explain },
    ],
    predictionPrompt,
    practiceItem: change,
    checkpoint: explain,
  }
}

function facts(definition: string, variable: string, observation: string): KeyFact[] {
  return [
    { label: 'Definition', value: definition },
    { label: 'Change', value: variable },
    { label: 'Observe', value: observation },
    { label: 'Rule', value: 'Sound needs vibrating matter, so changing the source or medium changes what is heard.' },
  ]
}

function quiz(prompt: string, answer: string, misconception: string): QuizQuestion[] {
  return [
    {
      prompt,
      options: [answer, misconception, 'The sound becomes visible matter', 'The listener becomes the source'],
      correctIndex: 0,
      explanation: answer,
      misconception,
    },
    {
      prompt: 'What should a learner change first in a sound lab?',
      options: ['One variable such as frequency, amplitude, or medium', 'Every variable at once', 'Only the background color', 'The quiz order'],
      correctIndex: 0,
      explanation: 'Sound cause and effect is clearest when frequency, amplitude, or medium is changed one at a time.',
      misconception: 'Changing everything together makes it hard to know why the sound changed.',
    },
    {
      prompt: 'What is the key evidence that sound is being made?',
      options: ['A vibration traveling through a medium', 'A still object with no motion', 'A silent vacuum carrying pressure pulses', 'A shadow on a wall'],
      correctIndex: 0,
      explanation: 'Sound starts with vibration and travels as pressure changes in matter.',
      misconception: 'Sound is not a separate substance; it is energy moving through a medium.',
    },
  ]
}

