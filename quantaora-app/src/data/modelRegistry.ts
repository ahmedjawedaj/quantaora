export const MODEL_ASSET_MANIFEST = MODEL_ASSETS.map((asset) => asset.url)

const BY_URL = new Map<string, ModelAssetRecord>()
const BY_BASENAME = new Map<string, ModelAssetRecord>()

for (const asset of MODEL_ASSETS) {
  BY_URL.set(asset.url, asset)
  const base = asset.url.split('/').pop() ?? ''
  if (!BY_BASENAME.has(base)) BY_BASENAME.set(base, asset)
}

export interface AssetResolution {
  requestedModel: string
  asset?: ModelAssetRecord
  resolvedUrl?: string
  status: 'ready' | 'missing'
}

export interface AssetCoverageSummary {
  total: number
  heroReady: number
  supportReady: number
  previewMissing: number
  paidLaunchRisk: number
  reviewNeeded: number
  status: 'hero-complete' | 'partial-hero' | 'preview-only' | 'empty'
}

export function resolveAuthoredAsset(model: string): AssetResolution {
  const requestedModel = model || ''
  if (!requestedModel) return { requestedModel, status: 'missing' }

  const direct = BY_URL.get(requestedModel)
  if (direct) {
    return {
      requestedModel,
      asset: direct,
      resolvedUrl: direct.url,
      status: 'ready',
    }
  }

  const base = requestedModel.split('/').pop() ?? ''
  const matched = BY_BASENAME.get(base)
  if (matched) {
    return {
      requestedModel,
      asset: matched,
      resolvedUrl: matched.url,
      status: 'ready',
    }
  }

  return { requestedModel, status: 'missing' }
}

/** Backward-compatible helper for viewers that only need a URL. */
export function resolveAuthoredModel(model: string): string | undefined {
  return resolveAuthoredAsset(model).resolvedUrl
}

export function assetStatusLabel(resolution: AssetResolution): string {
  if (resolution.status === 'missing') {
    return 'Preview model - premium GLB sourcing needed.'
  }

  const { asset } = resolution
  if (!asset) return 'Preview model - premium GLB sourcing needed.'

  if (asset.qualityTier === 'hero' && asset.licenseStatus === 'CLEAR') {
    return `Hero GLB ready - ${asset.sourceName}.`
  }

  if (asset.qualityTier === 'hero' && asset.licenseStatus === 'ATTRIB') {
    return `Hero GLB ready - attribution required.`
  }

  if (asset.licenseStatus === 'NC-RISK') {
    return 'High-quality GLB, but licence blocks paid launch replacement.'
  }

  if (asset.licenseStatus === 'REVIEW') {
    return 'Hero-quality GLB, but provenance needs final review.'
  }

  return 'Support GLB ready - useful, but below the flagship quality bar.'
}

export function componentAssetResolution(content: ComponentContent): AssetResolution {
  return resolveAuthoredAsset(content.model)
}

/**
 * True when a resolved asset's *legal* provenance is still `REVIEW` (see the
 * Status key in docs/ASSET-LICENSES.md): a real GLB is wired up and `status`
 * is `'ready'`, but source/licence/commercial-use/redistribution/attribution
 * have not been recorded yet. `resolveAuthoredAsset`'s `'ready' | 'missing'`
 * status is deliberately about *asset presence*, not licence clearance, so it
 * says nothing about this on its own — callers that need to gate on legal
 * readiness (e.g. BranchLab's generic, non-Anatomy branch views) should check
 * this explicitly rather than trusting `status === 'ready'` alone.
 */
export function isAssetReviewPending(resolution: AssetResolution): boolean {
  return resolution.status === 'ready' && resolution.asset?.licenseStatus === 'REVIEW'
}

export function summarizeComponentAssets(components: readonly ComponentContent[]): AssetCoverageSummary {
  const summary: AssetCoverageSummary = {
    total: components.length,
    heroReady: 0,
    supportReady: 0,
    previewMissing: 0,
    paidLaunchRisk: 0,
    reviewNeeded: 0,
    status: 'empty',
  }

  for (const component of components) {
    const resolution = componentAssetResolution(component)
    if (!resolution.asset) {
      summary.previewMissing += 1
      continue
    }

    if (resolution.asset.qualityTier === 'hero') {
      summary.heroReady += 1
    } else {
      summary.supportReady += 1
    }

    if (resolution.asset.licenseStatus === 'NC-RISK' || resolution.asset.replaceBeforePaidLaunch) {
      summary.paidLaunchRisk += 1
    }

    if (resolution.asset.licenseStatus === 'REVIEW') {
      summary.reviewNeeded += 1
    }
  }

  if (summary.total === 0) {
    summary.status = 'empty'
  } else if (summary.heroReady === summary.total && summary.paidLaunchRisk === 0 && summary.reviewNeeded === 0) {
    summary.status = 'hero-complete'
  } else if (summary.heroReady > 0) {
    summary.status = 'partial-hero'
  } else {
    summary.status = 'preview-only'
  }

  return summary
}
