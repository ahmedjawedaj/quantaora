import type { ComponentContent, KeyFact, QuizQuestion } from './types'

function lesson(predictionPrompt: string, change: string, observe: string, explain: string) {
  return {
    steps: [
      { title: 'Predict', body: predictionPrompt },
      { title: 'Change', body: change },
      { title: 'Observe', body: observe },
      { title: 'Explain', body: explain },
    ],
    predictionPrompt,
    practiceItem: change,
    checkpoint: explain,
  }
}

function facts(definition: string, variable: string, observation: string, apparatus: string): KeyFact[] {
  return [
    { label: 'Definition', value: definition },
    { label: 'Apparatus', value: apparatus },
    { label: 'Variable', value: variable },
    { label: 'Visible effect', value: observation },
    { label: 'Rule', value: 'Thermal energy moves from warmer places toward cooler places unless work moves it otherwise.' },
  ]
}

function quiz(prompt: string, answer: string, misconception: string): QuizQuestion[] {
  return [
    {
      prompt,
      options: [answer, misconception, 'Cold is a separate fluid that pours in', 'Temperature ignores particle motion'],
      correctIndex: 0,
      explanation: answer,
      misconception,
    },
    {
      prompt: 'How should a thermal experiment be changed?',
      options: ['Change one variable such as temperature, material, or surface color', 'Change every material and temperature at once', 'Only rename the sample', 'Remove the thermometer'],
      correctIndex: 0,
      explanation: 'One controlled change makes heat transfer or phase change evidence clear.',
      misconception: 'Changing many things together hides which thermal property caused the observation.',
    },
    {
      prompt: 'What direction does heat naturally transfer?',
      options: ['From warmer regions toward cooler regions', 'Always downward only', 'Only from smaller objects to larger objects', 'Only through metal'],
      correctIndex: 0,
      explanation: 'Net thermal energy transfer goes from higher temperature to lower temperature.',
      misconception: 'Heat direction is about temperature difference, not simply height, size, or material name.',
    },
  ]
}

