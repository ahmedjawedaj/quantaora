import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { mechanics } from '../data/generated/mechanics.ts'

// Regression guard for Wave 11 Worker 5's task: mechanics lesson/quiz copy instructs the child to
// "Tap `hs-cart`" / "Tap `hs-velocity-graph`" etc. -- leaking the internal hotspot *slug* (the raw
// id string used to key hotspots in code, e.g. "hs-cart") straight into copy a child reads,
// instead of the hotspot's human label ("Cart"). Confirmed live across all 13 mechanics
// components' lesson steps, not just Force.
//
// IMPORTANT: this file previously scanned `src/data/generated/mechanics.ts` directly and asserted
// zero `hs-*` occurrences in its prose -- that was the wrong target. `mechanics.ts` is
// `@generated by scripts/codegen -- do not edit by hand` and was explicitly out of every worker's
// ownership this wave, so the raw slugs sitting in that untouched source file are permanent and
// by design, not a bug. The actual fix Worker 5 landed lives entirely in `PhysicsLab.tsx`: a
// `sanitizeHotspotSlugs`/`sanitizeLessonContent` transform (in an `enhancedContent` useMemo) that
// looks up each `hs-*` id against that component's own `hotspots[].label` and substitutes natural
// phrasing (e.g. "the cart") before the content ever reaches `LessonModal`/`QuizModal`. So the
// regression guard belongs against PhysicsLab.tsx's *learner-facing output path* -- does the
// sanitizer exist, and is it actually what LessonModal/QuizModal render, not the raw generated
// import -- rather than against the untouched generated source, which will forever contain raw
// slugs regardless of whether the real fix is present or not.
//
// Static source-text checks only -- no jsdom/WebGL in this repo's test setup (see
// ../routes/BranchLab.test.ts's own comment on why).
//
// Run with: node --test src/routes/mechanicsLessonCopy.test.ts

function srcPath(relativeToThisFile: string): string {
  return fileURLToPath(new URL(relativeToThisFile, import.meta.url))
}

const physicsLabSrc = readFileSync(srcPath('./PhysicsLab.tsx'), 'utf8')

test('PhysicsLab: a hotspot-slug sanitizer exists (looks up hs-* ids against hotspot labels, not just strips them)', () => {
  // Accept any reasonably-named sanitizer function, but require it to actually reference the
  // `hs-` slug shape and a hotspot `label` lookup -- not just any function that happens to have
  // "sanitize" in its name for an unrelated purpose.
  const sanitizerFnMatch = physicsLabSrc.match(/function\s+(\w*[Ss]aniti[sz]e\w*)\s*\(/)
  assert.ok(
    sanitizerFnMatch,
    'expected PhysicsLab.tsx to define a hotspot-slug sanitizer function (e.g. sanitizeHotspotSlugs/sanitizeLessonContent)',
  )
  const sanitizerBody = physicsLabSrc.slice(sanitizerFnMatch!.index!, sanitizerFnMatch!.index! + 1500)
  assert.match(
    sanitizerBody,
    /hs-/,
    'expected the sanitizer to reference the hs-* slug pattern it is meant to catch',
  )
  assert.match(
    sanitizerBody,
    /\.label\b/,
    'expected the sanitizer to look up each hotspot\'s human-readable `label` (not just strip/blank the slug), so learner copy reads naturally instead of losing the reference entirely',
  )
})

test('PhysicsLab: the sanitized content, not the raw generated import, is what LessonModal/QuizModal actually render', () => {
  // Find the memo/derivative (commonly `enhancedContent`) that both (a) is built from calling the
  // sanitizer on the route's raw content, and (b) is what's actually passed as the `content` prop
  // to LessonModal and QuizModal -- i.e. the fix isn't just defined and unused elsewhere while the
  // modals still render the raw mechanics.ts import directly.
  const sanitizerCallMatch = physicsLabSrc.match(/(\w+)\s*=\s*(\w*[Ss]aniti[sz]e\w*)\s*\(/)
  assert.ok(
    sanitizerCallMatch,
    'expected the sanitizer function to actually be invoked somewhere (assigned to a variable), not just declared and unused',
  )
  const sanitizedVarName = sanitizerCallMatch![1]

  // The variable the sanitizer's result feeds into (or the sanitized value itself) must reach a
  // `content={...}` prop passed to both LessonModal and QuizModal. Allow either: the sanitizer's
  // own result variable is spread/used directly to build the final derivative passed as `content`,
  // so check for a variable that both derives from `sanitizedVarName` (or *is* it) and is the
  // `content=` prop value on both modals.
  const lessonModalPropMatch = physicsLabSrc.match(/<LessonModal\b[^>]*\bcontent=\{(\w+)\}/)
  const quizModalPropMatch = physicsLabSrc.match(/<QuizModal\b[^>]*\bcontent=\{(\w+)\}/)
  assert.ok(lessonModalPropMatch, 'expected <LessonModal> to receive a content={...} prop bound to a single identifier')
  assert.ok(quizModalPropMatch, 'expected <QuizModal> to receive a content={...} prop bound to a single identifier')

  const lessonContentVar = lessonModalPropMatch![1]
  const quizContentVar = quizModalPropMatch![1]
  assert.equal(
    lessonContentVar,
    quizContentVar,
    'expected LessonModal and QuizModal to be fed the same content derivative, so a fix applied for one necessarily covers the other',
  )

  // That shared content variable must itself be derived from (or be) the sanitizer's output --
  // i.e. its own declaration references sanitizedVarName (directly, or via a spread of it), not
  // the raw `mechanicsById`/`mechanics` import untouched. Located by index + a generous fixed
  // window (not a `)`-terminated regex): a `\)`-bounded capture stops at the *first* closing
  // paren, which for `useMemo(() => { ... }, [...])` is the empty arrow-param list's own `()`
  // right after `useMemo(`, zero characters in -- not the useMemo call's real closing paren.
  const declStartMatch = physicsLabSrc.match(new RegExp(`const\\s+${lessonContentVar}\\b[^=]*=\\s*useMemo\\(`))
  assert.ok(
    declStartMatch,
    `expected a useMemo building \`${lessonContentVar}\` (the value passed to LessonModal/QuizModal) in PhysicsLab.tsx`,
  )
  const declWindow = physicsLabSrc.slice(declStartMatch!.index!, declStartMatch!.index! + 1500)
  assert.match(
    declWindow,
    new RegExp(`\\b${sanitizedVarName}\\b`),
    `expected \`${lessonContentVar}\` (passed to LessonModal/QuizModal as content) to be derived from \`${sanitizedVarName}\` (the sanitizer's output), not built straight from the raw generated mechanics import -- otherwise the sanitizer exists but never actually reaches the rendered lesson/quiz copy`,
  )
})

test('mechanics.ts: sanity check -- lesson steps and hotspots are still intact in the raw generated data the sanitizer reads from', () => {
  // This deliberately still reads the raw generated file (not asserting it has no slugs -- see
  // the file-level comment above on why that's not this fix's target) -- just confirming the
  // sanitizer has real, structurally-intact hotspot/lesson data to work with, so the other two
  // tests above aren't accidentally passing because the content itself was gutted.
  assert.ok(mechanics.length >= 13, `expected at least 13 mechanics components, found ${mechanics.length}`)
  const withSteps = mechanics.filter((c) => (c.lesson?.steps?.length ?? 0) > 0)
  assert.equal(
    withSteps.length,
    mechanics.length,
    'expected every mechanics component to still have lesson steps authored',
  )
  const sampleWithHotspots = mechanics.find((c) => c.id === 'acceleration')
  assert.ok(sampleWithHotspots, 'expected the acceleration component to exist as a sample fixture')
  assert.ok(
    (sampleWithHotspots!.hotspots?.length ?? 0) >= 4,
    'expected acceleration to still have its hotspots array intact (hs-cart, hs-gas, hs-brake, hs-velocity-graph, hs-accel-arrow) -- the sanitizer needs these labels to substitute',
  )
})
