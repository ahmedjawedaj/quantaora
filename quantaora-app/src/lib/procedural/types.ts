/**
 * Procedural visual contract — the authored intent that tells the generic viewer
 * WHAT to compose when no real GLB exists. `shape` names a composition in
 * src/components/explorer/procedural/compositions.tsx; math components carry an
 * authored `visual` block in model-metadata.json (L2 of docs/PROCEDURAL-VISUALS.md).
 */
export interface ProceduralVisual {
  /** Composition id, e.g. "disc-torus", "number-line-rail", "place-value-blocks". */
  shape: string
  /** Authoring-only context (variables the visual responds to). Reserved for future sims. */
  variables?: string[]
  [key: string]: unknown
}

